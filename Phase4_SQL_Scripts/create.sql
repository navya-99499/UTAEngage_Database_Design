-- ============================================================
-- TRIGGER : Podcast.Subscribers_count
-- ============================================================
CREATE OR REPLACE TRIGGER trg_update_subscribers_count
AFTER INSERT OR DELETE ON DASC5306_Fall25_S001_T8_Subscribes
FOR EACH ROW
BEGIN
    IF INSERTING THEN
        UPDATE DASC5306_Fall25_S001_T8_Podcast
        SET subscribers_count = NVL(subscribers_count, 0) + 1
        WHERE podcast_ID = :NEW.podcast_ID;
    ELSIF DELETING THEN
        UPDATE DASC5306_Fall25_S001_T8_Podcast
        SET subscribers_count = NVL(subscribers_count, 0) - 1
        WHERE podcast_ID = :OLD.podcast_ID;
    END IF;
END;
/

-- ============================================================
-- TRIGGER : Episode.likes, Episode.dislikes, Episode.views
-- ============================================================
CREATE OR REPLACE TRIGGER trg_update_episode_engagement
AFTER INSERT OR DELETE OR UPDATE ON DASC5306_Fall25_S001_T8_Listens
FOR EACH ROW
BEGIN
    -- If a new listen is added → increment views
    IF INSERTING THEN
        UPDATE DASC5306_Fall25_S001_T8_Episode
        SET views = NVL(views, 0) + 1
        WHERE podcast_ID = :NEW.podcast_ID AND episodeNumber = :NEW.episodeNumber;

        IF :NEW.likes_dislikes = 1 THEN
            UPDATE DASC5306_Fall25_S001_T8_Episode
            SET likes = NVL(likes, 0) + 1
            WHERE podcast_ID = :NEW.podcast_ID AND episodeNumber = :NEW.episodeNumber;
        ELSIF :NEW.likes_dislikes = -1 THEN
            UPDATE DASC5306_Fall25_S001_T8_Episode
            SET dislikes = NVL(dislikes, 0) + 1
            WHERE podcast_ID = :NEW.podcast_ID AND episodeNumber = :NEW.episodeNumber;
        END IF;
    END IF;

    -- If listen is deleted → decrement counts
    IF DELETING THEN
        UPDATE DASC5306_Fall25_S001_T8_Episode
        SET views = NVL(views, 0) - 1
        WHERE podcast_ID = :OLD.podcast_ID AND episodeNumber = :OLD.episodeNumber;
        IF :OLD.likes_dislikes = 1 THEN
            UPDATE DASC5306_Fall25_S001_T8_Episode
            SET likes = NVL(likes, 0) - 1
            WHERE podcast_ID = :OLD.podcast_ID AND episodeNumber = :OLD.episodeNumber;
        ELSIF :OLD.likes_dislikes = -1 THEN
            UPDATE DASC5306_Fall25_S001_T8_Episode
            SET dislikes = NVL(dislikes, 0) - 1
            WHERE podcast_ID = :OLD.podcast_ID AND episodeNumber = :OLD.episodeNumber;
        END IF;
    END IF;
END;
/

